"""Generate linpad/npp_tables.py from REA outputs (menus.txt, keys.txt) + english.xml."""
import re, sys, pprint, xml.etree.ElementTree as ET
menus = open(sys.argv[1], encoding='utf-8').read().split('=== MENU ')
keys = open(sys.argv[2]).read().splitlines()
eng = ET.parse(sys.argv[3]).getroot()
sub_ids = {}
for it in eng.iter('Item'):
    if it.get('subMenuId'):
        sub_ids.setdefault(it.get('name').replace('&', '').lower(), it.get('subMenuId'))
main_ids = [it.get('menuId') for it in eng.find('.//Main/Entries')]
def parse(block):
    lines = block.splitlines()[1:]
    root = []; stack = [(-1, root)]
    for ln in lines:
        if not ln.strip(): continue
        ind = (len(ln) - len(ln.lstrip(' '))) // 2
        s = ln.strip()
        while stack[-1][0] >= ind: stack.pop()
        cur = stack[-1][1]
        if s.startswith('['):
            label = s[1:-1]; items = []
            cur.append(['sub', label, items]); stack.append((ind, items))
        elif s == '----': cur.append(['sep'])
        else:
            m = re.match(r'(\d+): (.*)', s); cur.append(['cmd', int(m.group(1)), m.group(2)])
    return root
main = parse(menus[1]); tray = parse(menus[2]); runvars = parse(menus[3])
# main menu: 12 top entries + "?" + the language compact variant; tail (＋ ▼ ✕) dropped
tops = [m for m in main if m[0] == 'sub' and m[1] != '▼']
lang_flat = tops[5]; lang_compact = tops[6]
tops = tops[:6] + tops[7:]
top_ids = ['file', 'edit', 'search', 'view', 'encoding', 'language', 'settings', 'tools', 'macro', 'run', 'Plugins', 'Window', '?']
def tag(items):
    out = []
    for it in items:
        if it[0] == 'sub':
            sid = sub_ids.get(it[1].replace('&', '').lower(), '')
            out.append(('sub', sid, it[1], tag(it[2])))
        elif it[0] == 'sep': out.append(('sep',))
        else: out.append(('cmd', it[1], it[2]))
    return out
MENUBAR = [(top_ids[i], t[1], tag(t[2])) for i, t in enumerate(tops)]
LANG_COMPACT = tag(lang_compact[2])
TRAY = tag(tray[0][2]); RUNVARS = [(c[1], c[2]) for c in runvars[0][2] if c[0] == 'cmd']
KEYS = {}
for k in keys:
    fid, sc = k.split('\t'); fid = int(fid)
    if sc:
        sc = re.sub(r'0x6([1-9])', lambda m: 'Num' + m.group(1), sc)
        KEYS.setdefault(fid, []).append(sc)
with open(sys.argv[4], 'w', encoding='utf-8') as f:
    f.write('# Generated by tools/rea/gen_tables.py from the RT_MENU resources and the\n')
    f.write('# built-in WinMenuKeyDefinition table recovered from notepad++.exe 8.9.6.2.\n')
    f.write('# Do not edit by hand.\n\n')
    for n, v in (('MENUBAR', MENUBAR), ('LANG_COMPACT', LANG_COMPACT), ('TRAY', TRAY), ('RUNVARS', RUNVARS), ('DEFAULT_KEYS', KEYS)):
        f.write(f'{n} = ' + pprint.pformat(v, width=110, sort_dicts=True) + '\n\n')
print(len(MENUBAR), len(KEYS))
